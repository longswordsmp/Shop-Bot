"""Generate reference documentation from the code itself, so it cannot drift:

- docs/COMMANDS.md        - every slash command, option, and required permission (from the command tree)
- docs/DATABASE.md        - every table and column (from the migrated schema)
- docs/CONTENT_CHECKLIST.md - every content key (same as ``python -m tools.checklist --write``)
- docs/COMPONENTS.md      - every button/menu/form route and its handler and access level

Usage:
    python -m tools.reference_docs
"""

from __future__ import annotations

import asyncio
import sqlite3
import sys
from typing import Any

from discord import app_commands

from shopbot.context import App
from shopbot.db.migrate import apply_migrations
from tools.checklist import CHECKLIST_PATH, build_checklist
from tools.offline import ROOT, build_offline_app

DOCS = ROOT / "docs"


def _command_rows(command: Any, prefix: str = "") -> list[tuple[str, Any]]:
    if isinstance(command, app_commands.Group):
        rows: list[tuple[str, Any]] = []
        for child in command.commands:
            rows.extend(_command_rows(child, f"{prefix}{command.name} "))
        return rows
    return [(f"/{prefix}{command.name}", command)]


def _access(command: Any) -> str:
    checks = getattr(command, "checks", [])
    names = " ".join(getattr(c, "__qualname__", "") for c in checks)
    if "require_admin" in names:
        return "admin"
    if "require_staff" in names:
        return "staff"
    return "-"


def commands_markdown(app: App) -> str:
    tree = app.bot.tree  # type: ignore[union-attr]
    lines = [
        "# Command reference",
        "",
        "Generated by `python -m tools.reference_docs` from the bot's command tree. All commands are staff or admin",
        'tools; customers use the panels. Access is enforced by the bot on every use ("admin" = owner, Discord',
        'Administrator, or a role in `permissions.admin_roles`; "staff" = admins plus staff roles). Default member',
        "permissions only control who sees the command in Discord's picker and can be adjusted per command, role,",
        "member or channel in Server Settings → Integrations → (the bot) → Manage. The shipped Staff role has",
        "Manage Messages (`server.roles` `staff` `permissions`), so staff see every command whose default visibility",
        "is manage_messages; `/product` (manage_guild) can be allowed for a role there (plus `catalog.manager_roles`).",
        "",
    ]
    commands = sorted(tree.get_commands(guild=app.guild_object), key=lambda c: c.name)
    menus = [c for c in commands if isinstance(c, app_commands.ContextMenu)]
    commands = [c for c in commands if not isinstance(c, app_commands.ContextMenu)]
    for top in commands:
        default_perms = getattr(top, "default_permissions", None)
        perms = ", ".join(name for name, value in default_perms if value) if default_perms is not None else "everyone"
        lines += [f"## /{top.name}", "", f"{top.description}", "", f"Default visibility: {perms}", ""]
        lines += ["| Command | Access | Description | Options |", "|---|---|---|---|"]
        for name, command in _command_rows(top):
            options = "; ".join(
                f"`{p.display_name}`{'' if p.required else ' (optional)'}: {p.description}" for p in command.parameters
            )
            lines.append(f"| `{name}` | {_access(command)} | {command.description} | {options or '-'} |")
        lines.append("")
    if menus:
        lines += ["## Message commands (right-click a message → Apps)", ""]
        lines += ["| Command | Access | Default visibility |", "|---|---|---|"]
        for menu in menus:
            default_perms = getattr(menu, "default_permissions", None)
            perms = (
                ", ".join(name for name, value in default_perms if value) if default_perms is not None else "everyone"
            )
            lines.append(f"| `{menu.name}` | {_access(menu)} | {perms} |")
        lines.append("")
    return "\n".join(lines)


def components_markdown(app: App) -> str:
    lines = [
        "# Interactive components",
        "",
        "Generated by `python -m tools.reference_docs`. Every button, menu, and form the bot sends carries a",
        "custom ID `sb:<route>:<action>[:<ids>]` that is routed to exactly one handler below. The router enforces",
        "the guild, the feature's readiness, rate limits, duplicate-click protection, and the access level before",
        "the handler runs; the handler then re-validates the record and the acting user (routes marked `any` that",
        "perform staff actions check staff status inside the handler, e.g. per-ticket-category staff roles).",
        "",
        "| Kind | Route | Action | Feature | Access | DM allowed | Handler |",
        "|---|---|---|---|---|---|---|",
    ]
    for route in sorted(app.router.routes(), key=lambda r: (r.route, r.action, r.kind)):
        handler = f"{route.handler.__module__}.{route.handler.__name__}"
        lines.append(
            f"| {route.kind} | `{route.route}` | `{route.action}` | {route.feature or '-'} | {route.access} | "
            f"{'yes' if route.allow_dm else 'no'} | `{handler}` |"
        )
    lines += ["", "## Scheduled task kinds", ""]
    lines += [f"- `{kind}`" for kind in app.scheduler.kinds]
    lines.append("")
    return "\n".join(lines)


def database_markdown() -> str:
    conn = sqlite3.connect(":memory:")
    apply_migrations(conn)
    lines = [
        "# Database schema",
        "",
        "Generated by `python -m tools.reference_docs` from the migrations in `shopbot/db/migrations`.",
        "All timestamps are UNIX seconds (UTC). All money columns (`*_minor`) are integers in the currency's minor",
        "unit (e.g. cents). Foreign keys are enforced. See `docs/DECISIONS.md` for the reasoning.",
        "",
    ]
    tables = [
        r[0]
        for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
        )
    ]
    for table in tables:
        lines += [f"## `{table}`", "", "| Column | Type | Not null | Default | Key |", "|---|---|---|---|---|"]
        for cid, name, ctype, notnull, default, pk in conn.execute(f'PRAGMA table_info("{table}")'):
            del cid
            lines.append(
                f"| `{name}` | {ctype} | {'yes' if notnull else ''} | {'' if default is None else default} | "
                f"{'PK' if pk else ''} |"
            )
        indexes = conn.execute(f'PRAGMA index_list("{table}")').fetchall()
        named = [row for row in indexes if not str(row[1]).startswith("sqlite_autoindex")]
        if named:
            lines += ["", "Indexes: " + ", ".join(f"`{row[1]}`{' (unique)' if row[2] else ''}" for row in named)]
        sql = conn.execute("SELECT sql FROM sqlite_master WHERE name = ?", (table,)).fetchone()[0]
        checks = [line.strip().rstrip(",") for line in sql.splitlines() if "CHECK" in line]
        if checks:
            lines += ["", "Constraints:", ""] + [f"- `{c}`" for c in checks]
        lines.append("")
    conn.close()
    return "\n".join(lines)


async def _run() -> int:
    app = await build_offline_app(ROOT / "config", content_mode="actual", all_features=True)
    try:
        DOCS.mkdir(exist_ok=True)
        (DOCS / "COMMANDS.md").write_text(commands_markdown(app), encoding="utf-8")
        (DOCS / "COMPONENTS.md").write_text(components_markdown(app), encoding="utf-8")
        (DOCS / "DATABASE.md").write_text(database_markdown(), encoding="utf-8")
        CHECKLIST_PATH.write_text(build_checklist(app, enabled_only=False), encoding="utf-8")
    finally:
        await app.db.close()
    for name in ("COMMANDS.md", "COMPONENTS.md", "DATABASE.md", "CONTENT_CHECKLIST.md"):
        print(f"Wrote docs/{name}")
    return 0


def main() -> int:
    return asyncio.run(_run())


if __name__ == "__main__":
    sys.exit(main())
